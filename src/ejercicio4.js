// Declarar una variable y almacenar en ella un valor numérico que representa el lado de un cuadrado.
// Calcular el área y el perímetro del cuadrado y mostrar los resultados por consola.
// Area = 2 * lado
// Perímetro = lado + lado + lado + lado
const lado = 5;
const area = lado * lado;
const perimetro = 4 * lado; 
console.log("El área del cuadrado es: " + area);
console.log("El perímetro del cuadrado es: " + perimetro);